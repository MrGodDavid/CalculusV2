    public static double tan(Radian angle) {
        for (TRIG_ANGLE_PAIR tanAnglePair : TAN_RADIANS_VALUE_TABLE) {
            if (angle.equals(tanAnglePair.angle)) {
                return tanAnglePair.value;
            }
        }
        return Math.sin(angle.val()) / Math.cos(angle.val());
    }
